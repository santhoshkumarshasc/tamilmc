let currentLang: LangCode = 'en';

export function lang(): LangCode {
  if (typeof localStorage !== 'undefined') {
    const saved = localStorage.getItem('tmc_lang');
    if (saved === 'ta' || saved === 'en') return saved;
  }
  return currentLang;
}

export function setLang(newLang: LangCode): void {
  currentLang = newLang;
  if (typeof localStorage !== 'undefined') {
    localStorage.setItem('tmc_lang', newLang);
  }
  applyTranslations();
  const event = new CustomEvent('tmc:langchange', { detail: { lang: newLang } });
  window.dispatchEvent(event);
}

export function t(key: string, vars?: Record<string, string | number>): string {
  const l = lang();
  let text = (I18N[l] && I18N[l][key]) || (I18N.en && I18N.en[key]) || key;
  if (vars) {
    Object.entries(vars).forEach(([k, v]) => {
      text = text.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v));
    });
  }
  return text;
}

export function applyTranslations(): void {
  if (typeof document === 'undefined') return;

  document.querySelectorAll<HTMLElement>('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (key) el.textContent = t(key);
  });

  document.querySelectorAll<HTMLInputElement | HTMLTextAreaElement>('[data-i18n-ph]').forEach(el => {
    const key = el.getAttribute('data-i18n-ph');
    if (key) el.placeholder = t(key);
  });

  document.querySelectorAll<HTMLElement>('[data-i18n-label]').forEach(el => {
    const key = el.getAttribute('data-i18n-label');
    if (key) el.setAttribute('aria-label', t(key));
  });

  document.querySelectorAll<HTMLElement>('[data-i18n-title]').forEach(el => {
    const key = el.getAttribute('data-i18n-title');
    if (key) el.setAttribute('title', t(key));
  });

  const langBtn = document.getElementById('langBtn');
  if (langBtn) {
    langBtn.textContent = lang() === 'ta' ? 'English' : 'தமிழ்';
  }

  const mLangVal = document.getElementById('mLangVal');
  if (mLangVal) {
    mLangVal.textContent = lang() === 'ta' ? 'English' : 'தமிழ்';
  }

  document.title = t('doc.title');
}

// Global window exposure for compatibility
declare global {
  interface Window {
    I18N: typeof I18N;
    lang: typeof lang;
    setLang: typeof setLang;
    t: typeof t;
    applyTranslations: typeof applyTranslations;
  }
}

if (typeof window !== 'undefined') {
  window.I18N = I18N;
  window.lang = lang;
  window.setLang = setLang;
  window.t = t;
  window.applyTranslations = applyTranslations;
}
